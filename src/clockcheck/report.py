"""Turn audits into a human-readable 'audit card' for a (clock, dataset) pair.

Voice: caveats first. The card leads with what could make the number wrong, not
with the number. A synthetic dataset gets a NON-EVIDENTIAL stamp it cannot lose.
"""
from __future__ import annotations
import json

import numpy as np
import pandas as pd

from . import audits
from .clocks import LinearClock
from .data import MethylationDataset


def build_audit_card(clock: LinearClock, ds: MethylationDataset,
                     compare_clocks: list[LinearClock] | None = None) -> dict:
    pred = clock.predict(ds.betas, on_missing="drop")
    card = {
        "clock": clock.spec.name,
        "citation": clock.spec.citation,
        "unit": clock.spec.unit,
        "dataset": ds.name,
        "n_samples": int(ds.betas.shape[1]),
        "is_synthetic": bool(ds.is_synthetic),
        "coverage": audits.cpg_coverage(clock, ds),
        "imputation_sensitivity": audits.imputation_sensitivity(clock, ds),
    }
    if clock.spec.unit == "years":
        card["calibration"] = audits.calibration_by_age(pred, ds.age)
        card["age_acceleration_fragility"] = audits.age_acceleration_fragility(pred, ds.age)
    if compare_clocks:
        years = [c for c in [clock, *compare_clocks] if c.spec.unit == "years"]
        preds = {c.spec.name: c.predict(ds.betas, on_missing="drop") for c in years}
        card["cross_clock_agreement"] = audits.cross_clock_agreement(preds)
    return card


def _fmt_pct(x: float) -> str:
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.1f}%"


def card_to_markdown(card: dict) -> str:
    L: list[str] = []
    L.append(f"# Audit card — {card['clock']} on {card['dataset']}")
    if card["is_synthetic"]:
        L.append("\n> **NON-EVIDENTIAL — SYNTHETIC DATA.** These numbers test the "
                 "pipeline only. Do not report or cite them as clock performance.\n")
    L.append(f"*{card['citation']}*  ·  unit: `{card['unit']}`  ·  n = {card['n_samples']}\n")

    cov = card["coverage"]
    L.append("## Coverage on this dataset")
    L.append(f"- CpGs present: **{cov['n_present']}/{cov['n_cpgs']}** "
             f"({_fmt_pct(cov['coverage_fraction'])})")
    L.append(f"- **Weight-weighted coverage: {_fmt_pct(cov['weight_coverage_fraction'])}** "
             "← the number the paper never shows")
    if cov["heaviest_missing_cpgs"]:
        top = list(cov["heaviest_missing_cpgs"].items())[:3]
        pretty = ", ".join(f"{k} (|w|={v:.3g})" for k, v in top)
        L.append(f"- Heaviest missing probes: {pretty}")

    imp = card["imputation_sensitivity"]
    L.append("\n## Imputation sensitivity (absent-CpG rule)")
    L.append(f"- Strategies compared: {', '.join(imp['strategies'])}")
    L.append(f"- Predicted-age swing per sample — median **{imp['median_spread_years']:.2f}**, "
             f"p95 **{imp['p95_spread_years']:.2f}**, max **{imp['max_spread_years']:.2f}** {card['unit']}")

    if "calibration" in card:
        cal = card["calibration"]
        L.append("\n## Calibration vs chronological age")
        L.append(f"- MAE **{cal['mae_years']:.2f}**, median bias **{cal['median_bias_years']:+.2f}** years")
        L.append(f"- Bias-vs-age slope **{cal['bias_vs_age_slope']:+.2f}** "
                 "(near -1 ⇒ regression-to-the-mean; extremes are distorted)")

    if "age_acceleration_fragility" in card:
        aa = card["age_acceleration_fragility"]
        L.append("\n## Age-acceleration fragility")
        L.append(f"- Correlation between two reasonable residual definitions: "
                 f"**{aa['corr_between_definitions']:.3f}** (1.0 would mean the choice is free)")

    if "cross_clock_agreement" in card and "median_range_years" in card["cross_clock_agreement"]:
        cc = card["cross_clock_agreement"]
        L.append("\n## Cross-clock agreement")
        L.append(f"- Clocks: {', '.join(cc['clocks'])}")
        L.append(f"- Median per-sample spread across clocks: **{cc['median_range_years']:.2f}** years")

    L.append("\n---\n*Generated by clockcheck. Audits describe reliability, not truth; "
             "a clean card is necessary, not sufficient.*")
    return "\n".join(L)


def _jsonable(obj):
    if isinstance(obj, (pd.DataFrame, pd.Series)):
        return json.loads(obj.to_json())
    if isinstance(obj, dict):
        return {k: _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (np.floating, np.integer)):
        return obj.item()
    return obj


def card_to_json(card: dict) -> str:
    return json.dumps(_jsonable(card), indent=2)
